-module(roadrunner_grpc_protobuf).
-moduledoc """
Protocol Buffers for `roadrunner_grpc`, with modules generated by
[gpb](https://github.com/tomas-abrahamsson/gpb).

`service/3` builds a service from what a gpb module knows of it, and the
module itself is the codec that encodes and decodes its messages:

```erlang
roadrunner_listener:start_link(my_listener, #{
    port => 50051,
    protocols => [http2],
    body_buffering => manual,
    routes => roadrunner_grpc:routes(#{
        services => [roadrunner_grpc_protobuf:service(helloworld_pb, 'helloworld.Greeter', greeter)],
        codecs => [roadrunner_grpc_protobuf]
    })
}).
```

`greeter` holds the methods, one function per method named after it in
snake case (`SayHello` is `say_hello/2`), called as
`roadrunner_grpc_service` describes with messages in the shape the gpb
module gives them: maps with its `maps` option, records without.

## The gpb module

The gpb module is generated with services (gpb's default) and its
introspection functions (also the default). Each method's message types
are `{GpbModule, MessageName}`, which is how the codec knows the module
to call: `GpbModule:encode_msg(Message, MessageName)` and
`GpbModule:decode_msg(Bytes, MessageName)`.
""".

-behaviour(roadrunner_grpc_codec).

-export([subtype/0, encode/2, decode/2]).
-export([service/3, service/4]).
-export([snake_case/1]).

-export_type([message_type/0, opts/0]).

-define(UPPER(C), (C >= $A andalso C =< $Z)).
-define(LOWER_OR_DIGIT(C), (C >= $a andalso C =< $z orelse C >= $0 andalso C =< $9)).

-doc "A method's message type: the gpb module and the message's name in it.".
-type message_type() :: {module(), atom()}.

-doc """
How `service/4` builds the service:

- `function_names`: how a method's function is named after it,
  `snake_case` (the default, `SayHello` is `say_hello`), `as_is`
  (`'SayHello'`), or a function from the method's name to the function's
- `unexported`: what to do with a method whose function the module does
  not export, `error` (the default, the routes fail to compile) or
  `unimplemented` (the method is left out, and a call to it is answered
  `UNIMPLEMENTED`)
""".
-type opts() :: #{
    function_names => snake_case | as_is | fun((binary()) -> atom()),
    unexported => error | unimplemented
}.

-doc "The `proto` subtype: `application/grpc` and `application/grpc+proto`.".
-spec subtype() -> binary().
subtype() ->
    ~"proto".

-doc "The bytes of `Message`, by the gpb module that knows its type.".
-spec encode(message_type(), term()) -> iodata().
encode({GpbModule, MessageName}, Message) ->
    GpbModule:encode_msg(Message, MessageName).

-doc "The message of type `MessageName` the bytes hold.".
-spec decode(message_type(), binary()) -> term().
decode({GpbModule, MessageName}, Bytes) ->
    GpbModule:decode_msg(Bytes, MessageName).

-doc "`service/4` with the default options.".
-spec service(module(), atom() | binary(), module()) -> roadrunner_grpc_service:descriptor().
service(GpbModule, Service, Module) ->
    service(GpbModule, Service, Module, #{}).

-doc """
The service `Service` of `GpbModule`, its methods in `Module`, for
`roadrunner_grpc:routes/1`'s `services`. `Service` is its name in the gpb
module (an atom, such as `'helloworld.Greeter'`) or its full gRPC name (a
binary, such as `~"helloworld.Greeter"`).

A `GpbModule` that is not a module that loads, or has no services, raises
`{invalid_gpb_module, GpbModule}`, a `Module` that is not an atom
`{invalid_module, Module}`, an unknown service
`{unknown_service, GpbModule, Service}`, and two methods whose functions
would have the same name `{duplicate_function, Function, Methods}`. Bad
options raise `{invalid_grpc_protobuf_opts, Opts}` when they are not a map,
`{invalid_grpc_protobuf_opt, Key, Value}` or
`{unknown_grpc_protobuf_opt, Key}`.
""".
-spec service(module(), atom() | binary(), module(), opts()) ->
    roadrunner_grpc_service:descriptor().
service(GpbModule, Service, Module, Opts) when is_atom(GpbModule), is_atom(Module), is_map(Opts) ->
    Naming = function_names(Opts),
    Unexported = unexported(Opts),
    ok = check_known_opts(Opts),
    ok = check_gpb_module(GpbModule),
    ServiceName = service_name(GpbModule, Service),
    Rpcs =
        case GpbModule:get_service_def(ServiceName) of
            {{service, ServiceName}, Defs} -> Defs;
            error -> error({unknown_service, GpbModule, Service})
        end,
    %% A module that does not load is the core's to refuse, as it would
    %% refuse a service module that does not.
    _ = code:ensure_loaded(Module),
    Methods = [rpc(GpbModule, ServiceName, Def, Naming) || Def <- Rpcs],
    ok = check_unique_functions(Methods),
    #{
        name => GpbModule:service_name_to_fqbin(ServiceName),
        module => Module,
        rpcs => maps:from_list([
            Method
         || {_, Rpc} = Method <- Methods, kept(Module, Rpc, Unexported)
        ])
    };
service(_GpbModule, _Service, _Module, Opts) when not is_map(Opts) ->
    error({invalid_grpc_protobuf_opts, Opts});
service(GpbModule, _Service, _Module, _Opts) when not is_atom(GpbModule) ->
    error({invalid_gpb_module, GpbModule});
service(_GpbModule, _Service, Module, _Opts) ->
    error({invalid_module, Module}).

%% A gpb module generated with services: `get_service_def/1` is what tells
%% them.
-spec check_gpb_module(module()) -> ok.
check_gpb_module(GpbModule) ->
    maybe
        {module, GpbModule} ?= code:ensure_loaded(GpbModule),
        true ?= erlang:function_exported(GpbModule, get_service_def, 1),
        ok
    else
        _ -> error({invalid_gpb_module, GpbModule})
    end.

%% Two methods sharing a function would both call it, whatever each one
%% expects.
-spec check_unique_functions([{binary(), roadrunner_grpc_service:rpc()}]) -> ok.
check_unique_functions(Methods) ->
    unique_functions(
        lists:keysort(1, [{Function, Method} || {Method, #{function := Function}} <- Methods])
    ).

-spec unique_functions([{atom(), binary()}]) -> ok.
unique_functions([{Function, A}, {Function, B} | _]) ->
    error({duplicate_function, Function, [A, B]});
unique_functions([_ | Rest]) ->
    unique_functions(Rest);
unique_functions([]) ->
    ok.

-spec check_known_opts(map()) -> ok.
check_known_opts(Opts) ->
    case maps:keys(maps:without([function_names, unexported], Opts)) of
        [] -> ok;
        [Key | _] -> error({unknown_grpc_protobuf_opt, Key})
    end.

-spec function_names(map()) -> snake_case | as_is | fun((binary()) -> atom()).
function_names(#{function_names := Naming}) when
    Naming =:= snake_case; Naming =:= as_is; is_function(Naming, 1)
->
    Naming;
function_names(#{function_names := Naming}) ->
    error({invalid_grpc_protobuf_opt, function_names, Naming});
function_names(#{}) ->
    snake_case.

-spec unexported(map()) -> error | unimplemented.
unexported(#{unexported := Unexported}) when Unexported =:= error; Unexported =:= unimplemented ->
    Unexported;
unexported(#{unexported := Unexported}) ->
    error({invalid_grpc_protobuf_opt, unexported, Unexported});
unexported(#{}) ->
    error.

%% The service's name in the gpb module: given as it is, or found by its
%% full gRPC name.
-spec service_name(module(), term()) -> atom().
service_name(_GpbModule, Service) when is_atom(Service) ->
    Service;
service_name(GpbModule, Service) when is_binary(Service) ->
    try
        GpbModule:fqbin_to_service_name(Service)
    catch
        error:_ -> error({unknown_service, GpbModule, Service})
    end;
service_name(GpbModule, Service) ->
    error({unknown_service, GpbModule, Service}).

%% A method, from gpb's map, `#rpc{}` record or proplist (the `maps`
%% option, neither, or `defs_as_proplists`).
-spec rpc(module(), atom(), term(), snake_case | as_is | fun((binary()) -> atom())) ->
    {binary(), roadrunner_grpc_service:rpc()}.
rpc(GpbModule, ServiceName, Def, Naming) ->
    {Name, Input, Output, InputStream, OutputStream} = rpc_fields(Def),
    {_, Method} = GpbModule:service_and_rpc_name_to_fqbins(ServiceName, Name),
    {Method, #{
        function => function_name(Naming, Method),
        kind => kind(InputStream, OutputStream),
        input => {GpbModule, Input},
        output => {GpbModule, Output}
    }}.

-spec rpc_fields(term()) -> {atom(), atom(), atom(), boolean(), boolean()}.
rpc_fields(#{
    name := Name,
    input := Input,
    output := Output,
    input_stream := InputStream,
    output_stream := OutputStream
}) ->
    {Name, Input, Output, InputStream, OutputStream};
rpc_fields({rpc, Name, Input, Output, InputStream, OutputStream, _Opts}) ->
    {Name, Input, Output, InputStream, OutputStream};
rpc_fields([{_, _} | _] = Def) ->
    case maps:from_list(Def) of
        #{name := _, input := _, output := _, input_stream := _, output_stream := _} = Rpc ->
            rpc_fields(Rpc);
        #{} ->
            error({unsupported_gpb_rpc_format, Def})
    end;
rpc_fields(Def) ->
    error({unsupported_gpb_rpc_format, Def}).

-spec kind(boolean(), boolean()) -> roadrunner_grpc_service:kind().
kind(false, false) -> unary;
kind(false, true) -> server_stream;
kind(true, false) -> client_stream;
kind(true, true) -> bidi_stream.

-spec kept(module(), roadrunner_grpc_service:rpc(), error | unimplemented) -> boolean().
kept(_Module, _Rpc, error) ->
    true;
kept(Module, #{function := Function, kind := Kind}, unimplemented) ->
    erlang:function_exported(Module, Function, arity(Kind)).

-spec arity(roadrunner_grpc_service:kind()) -> 1 | 2.
arity(Kind) when Kind =:= unary; Kind =:= server_stream -> 2;
arity(_Kind) -> 1.

-spec function_name(snake_case | as_is | fun((binary()) -> atom()), binary()) -> atom().
function_name(snake_case, Method) -> list_to_atom(snake_case(binary_to_list(Method)));
function_name(as_is, Method) -> binary_to_atom(Method);
function_name(Naming, Method) -> Naming(Method).

%% `SayHello` is `say_hello`, `HTTPGet` `http_get`, `GetV2` `get_v2`: a word
%% starts at a capital after a lowercase letter or a digit, and at the last
%% capital of a run followed by a lowercase letter.
-doc false.
-spec snake_case(string()) -> string().
snake_case([A, B | Rest]) when ?LOWER_OR_DIGIT(A), ?UPPER(B) ->
    [A, $_ | snake_case([B | Rest])];
snake_case([A, B, C | Rest]) when ?UPPER(A), ?UPPER(B), C >= $a, C =< $z ->
    [lower(A), $_ | snake_case([B, C | Rest])];
snake_case([A | Rest]) ->
    [lower(A) | snake_case(Rest)];
snake_case([]) ->
    [].

-spec lower(char()) -> char().
lower(C) when ?UPPER(C) -> C + 32;
lower(C) -> C.
