%% The current IMF-fixdate (`roadrunner_http:http_date_now/0`): a
%% `persistent_term` read and five table lookups, or, with no clock
%% running, the system time formatted.
-spec date() -> binary().
date() ->
    case stamp() of
        undefined -> format(erlang:system_time(second));
        Stamp -> stamp_to_date(Stamp)
    end.

%% Any Posix time as an IMF-fixdate (`roadrunner_http:format_http_date/1`).
-spec format(integer()) -> binary().
format(Posix) when Posix >= 0, Posix < ?STAMP_END ->
    stamp_to_date(stamp(Posix));
format(Posix) ->
    %% Outside the years the tables cover (1970 to 2225).
    Days = floor_div(Posix, 86400),
    SecOfDay = Posix - Days * 86400,
    {Y, M, D} = civil_from_days(Days),
    %% 1970-01-01 was a Thursday, index 3 in the Monday-first table.
    DayName = element(floor_mod(Days + 3, 7) + 1, ?DAY_NAMES),
    MonthName = element(M, ?MONTH_NAMES),
    <<DayName/binary, ", ", (pad2(D))/binary, " ", MonthName/binary, " ",
        (integer_to_binary(Y))/binary, " ", (pad2(SecOfDay div 3600))/binary, ":",
        (pad2(SecOfDay rem 3600 div 60))/binary, ":", (pad2(SecOfDay rem 60))/binary, " GMT">>.

%% Proleptic Gregorian date for a count of days since 1970-01-01, after
%% Howard Hinnant's `civil_from_days`. Done here rather than through
%% `calendar` so the first response doesn't pay for loading that module:
%% startup time is dominated by code loading.
-spec civil_from_days(integer()) -> {integer(), 1..12, 1..31}.
civil_from_days(Days) ->
    Z = Days + 719468,
    Era = floor_div(Z, 146097),
    DayOfEra = Z - Era * 146097,
    YearOfEra = (DayOfEra - DayOfEra div 1460 + DayOfEra div 36524 - DayOfEra div 146096) div 365,
    DayOfYear = DayOfEra - (365 * YearOfEra + YearOfEra div 4 - YearOfEra div 100),
    MarchMonth = (5 * DayOfYear + 2) div 153,
    D = DayOfYear - (153 * MarchMonth + 2) div 5 + 1,
    case MarchMonth < 10 of
        true -> {YearOfEra + Era * 400, MarchMonth + 3, D};
        false -> {YearOfEra + Era * 400 + 1, MarchMonth - 9, D}
    end.

-spec floor_div(integer(), pos_integer()) -> integer().
floor_div(N, Div) when N >= 0 -> N div Div;
floor_div(N, Div) -> -((Div - 1 - N) div Div).

-spec floor_mod(integer(), pos_integer()) -> non_neg_integer().
floor_mod(N, Div) -> N - floor_div(N, Div) * Div.

%% Two-digit zero-padded integer for the IMF-fixdate fields. Year is
%% 4-digit for modern timestamps, so `integer_to_binary/1` suffices
%% there; only the day/hour/minute/second need the leading-zero pad
%% when < 10.
-spec pad2(0..99) -> binary().
pad2(N) when N < 10 -> <<$0, ($0 + N)>>;
pad2(N) -> integer_to_binary(N).

%% The current second packed into one small integer, as this process
%% last wrote it, or `undefined` when no clock runs.
%% A small integer is an immediate on 64-bit emulators, so replacing it
%% every second never triggers the global GC scan a `persistent_term`
%% update otherwise costs. HTTP/1 caches its whole `date:` line per
%% connection keyed by this value. The layout, from the least
%% significant bit, each field a 1-based index into its table above:
%%
%%     second        6 bits  shift  0
%%     hour:minute  11 bits  shift  6
%%     year          9 bits  shift 17
%%     day+month     9 bits  shift 26
%%     weekday       3 bits  shift 35
-spec stamp() -> stamp() | undefined.
stamp() ->
    persistent_term:get(?STAMP_KEY, undefined).

%% Store the stamp for `Posix`, called by `tick/0` once a second.
%% Outside the years the tables cover it stores `undefined`,
%% sending readers to the slower system-time path. A clock that stops
%% calls `clear_stamp/0`: a stale stamp outlives its writer and
%% would serve a frozen date.
-spec put_stamp(integer()) -> ok.
put_stamp(Posix) when Posix >= 0, Posix < ?STAMP_END ->
    persistent_term:put(?STAMP_KEY, stamp(Posix));
put_stamp(_Posix) ->
    clear_stamp().

%% Writes the atom `undefined` rather than erasing the key: replacing
%% an immediate with an immediate skips the global GC scan, an erase
%% does not.
-spec clear_stamp() -> ok.
clear_stamp() ->
    persistent_term:put(?STAMP_KEY, undefined).

%% The 29-byte IMF-fixdate a stamp stands for: five table lookups,
%% each written as a fixed-width integer segment.
-spec stamp_to_date(stamp()) -> <<_:232>>.
stamp_to_date(Stamp) ->
    <<
        (element(Stamp bsr 35, ?DATE_WEEKDAYS)):40,
        (element((Stamp bsr 26) band 511, ?DATE_DAY_MONTHS)):56,
        (element((Stamp bsr 17) band 511, ?DATE_YEARS)):40,
        (element((Stamp bsr 6) band 2047, ?DATE_HOUR_MINUTES)):48,
        (element(Stamp band 63, ?DATE_SECONDS)):48
    >>.

-spec stamp(0..?STAMP_LAST) -> stamp().
stamp(Posix) ->
    Days = Posix div 86400,
    SecOfDay = Posix rem 86400,
    {Y, M, D} = civil_from_days(Days),
    %% 1970-01-01 was a Thursday, index 4 in the Monday-first table.
    (((Days + 3) rem 7 + 1) bsl 35) bor
        (((M - 1) * 31 + D) bsl 26) bor
        ((Y - 1969) bsl 17) bor
        ((SecOfDay div 60 + 1) bsl 6) bor
        (SecOfDay rem 60 + 1).

