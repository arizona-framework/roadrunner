%% Store this second's stamp and aim the next tick. The millisecond
%% clocks are read before the second: if a boundary falls in between,
%% the next tick aims at a boundary already past and fires at once,
%% rewriting the same second. Reading them after could aim a second too
%% far and leave a second unwritten.
-spec tick() -> reference().
tick() ->
    Mono = erlang:monotonic_time(millisecond),
    Ms = erlang:system_time(millisecond),
    ok = put_stamp(erlang:system_time(second)),
    Next = Mono + 1000 - Ms rem 1000 + 1,
    erlang:start_timer(Next, self(), tick, [{abs, true}]).
