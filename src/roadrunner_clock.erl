-module(roadrunner_clock).
-moduledoc false.

%% Keeps the `Date` header's date stamp fresh.
%%
%% Once a second this process packs the current time into one small
%% integer and stores it in `persistent_term` (`put_stamp/1`). Every
%% response then builds its `Date` value from there, in any process,
%% instead of each process formatting the time itself. HTTP/2 and HTTP/3 run every request in a fresh stream worker,
%% so a per-process cache would never hit for them.
%%
%% Ticks use an absolute timer aimed one millisecond past the next
%% second boundary, so they do not drift. The timer reference is the
%% state and is checked on expiry, so a stray `tick` is ignored. Exits
%% are trapped so `terminate/2` clears the stamp on shutdown: a stamp
%% outlives its writer, and a stale one would serve a frozen date. After
%% a kill the supervisor's restart rewrites it.

-behaviour(gen_server).

-export([start_link/0, date/0, format/1]).
-export([stamp/0, put_stamp/1, clear_stamp/0, stamp_to_date/1]).
-export([init/1, handle_call/3, handle_cast/2, handle_info/2, terminate/2]).

-export_type([stamp/0]).

%% One second packed for `stamp_to_date/1`; see `stamp/0`.
-type stamp() :: non_neg_integer().

%% An atom, not a `{?MODULE, Name}` tuple: `persistent_term:get/2`
%% hashes the key on every read, and a tuple key measured about 6 ns
%% slower per read than an atom.
-define(STAMP_KEY, roadrunner_date_stamp).
%% 2226-01-01T00:00:00Z, the first second past `DATE_YEARS`.
-define(STAMP_END, 8078572800).
-define(STAMP_LAST, 8078572799).

%% Lookup tables for `stamp_to_date/1`: fixed calendar data, generated
%% once; `roadrunner_http_tests` checks every entry against `calendar`.
%% Each entry is one field's ASCII bytes, separator included, as a
%% big-endian integer (16#4D6F6E2C20 is "Mon, "). Integer segments of a
%% known width let the compiler size the 29-byte result up front and
%% write each field as a word; the same tables as binaries measured over
